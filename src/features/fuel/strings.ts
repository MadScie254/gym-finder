const COPY: Record<Lang, FuelCopy> = { en, sw };

export function fuelCopy(lang: Lang): FuelCopy {
  return COPY[lang];
}

/** The language chosen elsewhere in the app, read once per screen. */
export function useFuelCopy(): FuelCopy {
  const [lang] = useState<Lang>(() => loadLanguage());
  return COPY[lang];
}

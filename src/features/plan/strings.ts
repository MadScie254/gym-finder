const COPY: Record<Lang, PlanCopy> = { en, sw };

export function planCopy(lang: Lang): PlanCopy {
  return COPY[lang];
}

export function usePlanCopy(): { copy: PlanCopy; lang: Lang } {
  const [lang] = useState<Lang>(() => loadLanguage());
  return { copy: COPY[lang], lang };
}

#!/usr/bin/env python3
"""Turns the downloaded Pexels originals into the WebP files the app serves.

For each entry in sources.json this reads <raw dir>/<pexelsId>.jpg, applies the optional crop, writes the
widths in WIDTHS (or the entry's own "widths", at the entry's own "quality") to public/photos/<slug>-<width>-<hash>.webp (the hash is of the file's bytes, so a changed
picture gets a new name and the old one can be cached for a year), and writes src/assets/photos.ts.

Run it with isolated mode, because the raw directory holds files downloaded from the internet:

    python3 -I scripts/photos/process.py --raw /path/to/originals

Needs Pillow with WebP support. See scripts/photos/README.md.
"""
import argparse
import hashlib
import io
import json
import pathlib
import sys

from PIL import Image

WIDTHS = (480, 800, 1200)
QUALITY = 72
ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ROOT / "scripts" / "photos" / "sources.json"
OUT_DIR = ROOT / "public" / "photos"
TS_OUT = ROOT / "src" / "assets" / "photos.ts"
CREDITS_OUT = ROOT / "docs" / "PHOTO_CREDITS.md"
LICENCE = "Pexels License"


def tone_of(image: Image.Image) -> str:
    """The picture's average colour, shown behind it while it loads."""
    r, g, b = image.resize((1, 1), Image.LANCZOS).getpixel((0, 0))
    return f"#{r:02x}{g:02x}{b:02x}"


def encode(image: Image.Image, width: int, quality: int) -> bytes:
    height = round(image.height * width / image.width)
    resized = image.resize((width, height), Image.LANCZOS)
    buffer = io.BytesIO()
    # Saving without an exif argument drops the camera and location data the original carries.
    resized.save(buffer, format="WEBP", quality=quality, method=6)
    return buffer.getvalue()


def process(entry: dict, raw: pathlib.Path) -> dict:
    source = raw / f"{entry['pexelsId']}.jpg"
    if not source.is_file():
        sys.exit(f"missing original: {source}")
    image = Image.open(source).convert("RGB")
    if "crop" in entry:
        left, top, right, bottom = entry["crop"]
        image = image.crop((round(left * image.width), round(top * image.height), round(right * image.width), round(bottom * image.height)))

    files = []
    quality = entry.get("quality", QUALITY)
    for width in entry.get("widths", WIDTHS):
        if width > image.width:
            continue
        data = encode(image, width, quality)
        digest = hashlib.sha1(data).hexdigest()[:8]
        name = f"{entry['slug']}-{width}-{digest}.webp"
        (OUT_DIR / name).write_bytes(data)
        files.append({"w": width, "src": f"/photos/{name}", "bytes": len(data)})

    # Remove this picture's older files, so a re-run does not leave unreferenced copies behind.
    keep = {pathlib.PurePosixPath(f["src"]).name for f in files}
    for old in OUT_DIR.glob(f"{entry['slug']}-*.webp"):
        if old.name not in keep:
            old.unlink()

    largest = files[-1]
    height = round(image.height * largest["w"] / image.width)
    credit = {"title": entry["title"], "author": entry["author"], "page": entry["page"], "licence": LICENCE}
    if "authorUrl" in entry:
        credit["authorUrl"] = entry["authorUrl"]
    return {
        "uses": entry["uses"],
        "id": entry["slug"],
        "alt": entry["alt"],
        "width": largest["w"],
        "height": height,
        "tone": tone_of(image),
        "focus": entry["focus"],
        "files": files,
        "credit": credit,
    }


def ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def write_ts(entries: list) -> None:
    ids = " | ".join(ts_string(e["id"]) for e in entries)
    lines = [
        "// Generated by scripts/photos/process.py from scripts/photos/sources.json. Do not edit by hand.",
        "// Every picture is a free-licence stock photograph used as an illustration. None shows a listed gym.",
        "",
        f"export type PhotoId = {ids};",
        "",
        "export type PhotoCredit = {",
        "  title: string;",
        "  author: string;",
        "  authorUrl?: string;",
        "  page: string;",
        "  licence: string;",
        "};",
        "",
        "export type PhotoFile = { w: number; src: string };",
        "",
        "export type PhotoEntry = {",
        "  alt: string;",
        "  /** Size of the largest file. The files share one shape. */",
        "  width: number;",
        "  height: number;",
        "  /** The picture's average colour, shown behind it while it loads. */",
        "  tone: string;",
        "  /** CSS object-position that keeps the subject in frame when the picture is cropped to a band. */",
        "  focus: string;",
        "  /** Narrowest first. */",
        "  files: readonly PhotoFile[];",
        "  credit: PhotoCredit;",
        "};",
        "",
        "export const PHOTOS: Record<PhotoId, PhotoEntry> = {",
    ]
    for e in entries:
        lines.append(f"  {ts_string(e['id'])}: {{")
        lines.append(f"    alt: {ts_string(e['alt'])},")
        lines.append(f"    width: {e['width']},")
        lines.append(f"    height: {e['height']},")
        lines.append(f"    tone: {ts_string(e['tone'])},")
        lines.append(f"    focus: {ts_string(e['focus'])},")
        lines.append("    files: [")
        for f in e["files"]:
            lines.append(f"      {{ w: {f['w']}, src: {ts_string(f['src'])} }},")
        lines.append("    ],")
        lines.append("    credit: {")
        c = e["credit"]
        lines.append(f"      title: {ts_string(c['title'])},")
        lines.append(f"      author: {ts_string(c['author'])},")
        if "authorUrl" in c:
            lines.append(f"      authorUrl: {ts_string(c['authorUrl'])},")
        lines.append(f"      page: {ts_string(c['page'])},")
        lines.append(f"      licence: {ts_string(c['licence'])},")
        lines.append("    },")
        lines.append("  },")
    lines.append("};")
    lines.append("")
    lines.append("export const PHOTO_IDS = Object.keys(PHOTOS) as PhotoId[];")
    lines.append("")
    TS_OUT.write_text("\n".join(lines), encoding="utf-8")


def write_credits(entries: list) -> None:
    lines = [
        "# Photo credits",
        "",
        "Generated by scripts/photos/process.py from scripts/photos/sources.json. Do not edit by hand.",
        "",
        f"Every photograph in public/photos is a free stock picture from Pexels, used under the Pexels License (https://www.pexels.com/license/): free to use and change, with no attribution required. We credit the photographers anyway, here and on the About page.",
        "",
        "These are illustrations. None of them shows a gym in the list, a meal from a store, or anyone connected to this app.",
        "",
        "| Picture | Photographer | Pexels page | Used for |",
        "|---|---|---|---|",
    ]
    for e in entries:
        c = e["credit"]
        author = f"[{c['author']}]({c['authorUrl']})" if "authorUrl" in c else c["author"]
        lines.append(f"| {c['title']} (`{e['id']}`) | {author} | [{c['page'].rstrip('/').split('/')[-1]}]({c['page']}) | {e['uses']} |")
    lines.append("")
    CREDITS_OUT.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw", required=True, type=pathlib.Path, help="directory holding <pexelsId>.jpg originals")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    sources = sorted(json.loads(SOURCES.read_text(encoding="utf-8")), key=lambda e: e["slug"])
    entries = [process(entry, args.raw) for entry in sources]
    write_ts(entries)
    write_credits(entries)

    total = 0
    for e in entries:
        sizes = ", ".join(f"{f['w']}w {f['bytes'] / 1024:.0f} KB" for f in e["files"])
        total += sum(f["bytes"] for f in e["files"])
        print(f"{e['id']:<18} {e['width']}x{e['height']}  {e['tone']}  {sizes}")
    print(f"{len(entries)} pictures, {total / 1024:.0f} KB in all")


if __name__ == "__main__":
    main()
